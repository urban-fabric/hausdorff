//! Base-cell data tables.
//!
//! The 122 H3 base cells and their topology — standard H3 data (the values
//! published by Uber's H3 reference and mirrored by h3o), lifted verbatim.

use super::coord::CoordIJK;

/// Number of base cells.
pub(super) const COUNT: u8 = 122;

/// Bitmap where bit `b` is set iff base cell `b` is a pentagon.
const BASE_PENTAGONS: u128 = 0x0020_0802_0008_0100_8402_0040_0100_4010;

/// Returns true iff the given base cell is one of the 12 pentagons.
pub(super) const fn is_pentagon(base_cell: u8) -> bool {
    BASE_PENTAGONS & (1u128 << base_cell) != 0
}

/// Pentagons where all neighbors orient towards it (the two polar pentagons).
pub(super) const fn is_polar_pentagon(base_cell: u8) -> bool {
    base_cell == 4 || base_cell == 117
}

/// Home face for a base cell.
pub(super) fn home_face(base_cell: u8) -> usize {
    METADATA[base_cell as usize].home as usize
}

/// Home FaceIJK coordinate for a base cell.
pub(super) fn home_coord(base_cell: u8) -> CoordIJK {
    METADATA[base_cell as usize].coord
}

/// Whether `face` is a CW-offset face for this (pentagon) base cell.
pub(super) fn is_cw_offset(base_cell: u8, face: usize) -> bool {
    match METADATA[base_cell as usize].cw_offset {
        Some((a, b)) => a as usize == face || b as usize == face,
        None => false,
    }
}

/// Direction-to-face mapping for a pentagon, indexed by directions J..=I
/// (direction digit minus 2).
pub(super) fn pentagon_direction_faces(base_cell: u8) -> [usize; 5] {
    debug_assert!(is_pentagon(base_cell));
    let mut index = 0usize;
    let mut candidate = 0u8;
    while candidate < base_cell {
        if is_pentagon(candidate) {
            index += 1;
        }
        candidate += 1;
    }
    PENTAGON_DIRECTION_FACES[index]
}

/// Neighboring base cell in the given direction digit (0..=6), or `None`.
pub(super) fn neighbor(base_cell: u8, digit: u8) -> Option<u8> {
    let v = NEIGHBORS[base_cell as usize][digit as usize];
    (v != 0xff).then_some(v)
}

/// 60° CCW rotations to the neighbor's coordinate system in the given direction.
pub(super) fn neighbor_rotation(base_cell: u8, digit: u8) -> u8 {
    NEIGHBOR_60CCW_ROTS[base_cell as usize][digit as usize]
}

/// Direction digit from `base_cell` to `neighbor`, if they are neighbors.
pub(super) fn direction_to(base_cell: u8, neighbor: u8) -> Option<u8> {
    NEIGHBORS[base_cell as usize]
        .iter()
        .position(|&c| c == neighbor)
        .map(|d| d as u8)
}

struct Meta {
    home: u8,
    coord: CoordIJK,
    cw_offset: Option<(u8, u8)>,
}

const fn m(home: u8, i: i32, j: i32, k: i32) -> Meta {
    Meta {
        home,
        coord: CoordIJK::new(i, j, k),
        cw_offset: None,
    }
}
const fn mp(home: u8, i: i32, j: i32, k: i32, a: u8, b: u8) -> Meta {
    Meta {
        home,
        coord: CoordIJK::new(i, j, k),
        cw_offset: Some((a, b)),
    }
}

